def mirror_endpoints():
    """하프미러 앞 아래 모서리와 뒤 위 모서리 (y, z)."""
    t = math.radians(MIRROR["tilt_deg"])
    y0, z0 = MIRROR["y_front"], MIRROR["z_front"]
    return (y0, z0), (y0 + MIRROR["length"] * math.sin(t), z0 - MIRROR["length"] * math.cos(t))


def mirror_normal():
    """반사면 법선 (y, z) — 위로 가는 빛을 뒤(-z)로 꺾는 방향."""
    t = math.radians(MIRROR["tilt_deg"])
    return (math.cos(t), math.sin(t))


